export function isDecision16RenditionSelectionV8(
  selection: PlayerPhotoSelectionV8,
): selection is PlayerPhotoDecision16SelectionV8 {
  return (
    isObject(selection) &&
    "decision16Rendition" in selection &&
    hasDecision16RenditionRecordShape(selection.decision16Rendition)
  );
}

