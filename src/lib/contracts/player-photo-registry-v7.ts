export interface PlayerPhotoRegistryV7ValidationInput {
  expectedAthleteCases: ReadonlyMap<string, readonly string[]>;
  expectedRegistrySha256: string;
  localAssetBytesByPath: ReadonlyMap<string, Uint8Array>;
  phase1EvidenceBytes: string;
  phase2EvidenceBytes: string;
  policyJsonBytes: string;
  policyMarkdownBytes: string;
  predecessorRegistryBytes: string;
  registryBytes: string;
}

export interface PlayerPhotoRegistryV7ValidationResult {
  issues: ValidationIssue[];
  registry: PlayerPhotoRegistryV7 | null;
}

const SHA1_RE = /^[a-f0-9]{40}$/u;

function exact(value: unknown, expected: unknown): boolean {
  return canonicalJson(value) === canonicalJson(expected);
}

function sameSortedSet(
  actual: readonly string[],
  expected: readonly string[],
): boolean {
  const left = [...actual].sort(compareCodePoints);
  const right = [...expected].sort(compareCodePoints);
  return (
    new Set(actual).size === actual.length &&
    left.length === right.length &&
    left.every((value, index) => value === right[index])
  );
}

function sha1Hex(bytes: Uint8Array): string {
  return createHash("sha1").update(bytes).digest("hex");
}

function malformedIssue(message: string): ValidationIssue {
  return issue(
    "player-photo-v7-schema",
    PLAYER_PHOTO_REGISTRY_V7_PATH,
    message,
  );
}

export function validatePlayerPhotoRegistryV7(
  input: PlayerPhotoRegistryV7ValidationInput,
): PlayerPhotoRegistryV7ValidationResult {
  const issues: ValidationIssue[] = [];
  let parsed: unknown;
  let predecessorParsed: unknown;
  try {
    parsed = parseStrictJson(input.registryBytes);
    predecessorParsed = parseStrictJson(input.predecessorRegistryBytes);
  } catch (error) {
    return {
      issues: [
        malformedIssue(error instanceof Error ? error.message : String(error)),
      ],
      registry: null,
    };
  }

  if (canonicalJson(parsed) !== input.registryBytes) {
    issues.push(
      issue(
        "player-photo-v7-canonical-json",
        PLAYER_PHOTO_REGISTRY_V7_PATH,
        "registry v7 must be canonical JSON",
      ),
    );
  }
  if (sha256Hex(input.registryBytes) !== input.expectedRegistrySha256) {
    issues.push(
      issue(
        "player-photo-v7-same-version-drift",
        PLAYER_PHOTO_REGISTRY_V7_PATH,
        "registry v7 bytes differ from the expected same-version digest",
      ),
    );
  }
  if (
    sha256Hex(input.predecessorRegistryBytes) !==
    PLAYER_PHOTO_REGISTRY_V7_PREDECESSOR.sha256
  ) {
    issues.push(
      issue(
        "player-photo-v7-predecessor-drift",
        PLAYER_PHOTO_REGISTRY_V7_PREDECESSOR.path,
        "the immutable registry v6 predecessor changed",
      ),
    );
  }
  if (
    sha256Hex(input.policyJsonBytes) !==
      PLAYER_PHOTO_POLICY_V8_BINDING.jsonSha256 ||
    sha256Hex(input.policyMarkdownBytes) !==
      PLAYER_PHOTO_POLICY_V8_BINDING.markdownSha256
  ) {
    issues.push(
      issue(
        "player-photo-v7-policy-binding",
        "sourcePolicyBinding",
        "the exact nba-v8 JSON and Markdown bytes are required",
      ),
    );
  }
  if (
    sha256Hex(input.phase1EvidenceBytes) !==
      PLAYER_PHOTO_REGISTRY_V7_PHASE_EVIDENCE.phase1.sha256 ||
    sha256Hex(input.phase2EvidenceBytes) !==
      PLAYER_PHOTO_REGISTRY_V7_PHASE_EVIDENCE.phase2.sha256
  ) {
    issues.push(
      issue(
        "player-photo-v7-phase-evidence-binding",
        "phaseEvidenceBindings",
        "the frozen Decision 15 Phase 1 and Phase 2 evidence bytes are required",
      ),
    );
  }

  if (
    parsed === null ||
    typeof parsed !== "object" ||
    Array.isArray(parsed) ||
    predecessorParsed === null ||
    typeof predecessorParsed !== "object" ||
    Array.isArray(predecessorParsed)
  ) {
    issues.push(
      malformedIssue("registry and predecessor roots must be objects"),
    );
    return { issues, registry: null };
  }

  const registry = parsed as PlayerPhotoRegistryV7;
  const predecessor = predecessorParsed as PlayerPhotoRegistryV6;
  if (
    registry.schemaVersion !== 7 ||
    registry.scopeId !== PLAYER_PHOTO_REGISTRY_V7_SCOPE_ID ||
    !exact(
      registry.predecessorRegistryBinding,
      PLAYER_PHOTO_REGISTRY_V7_PREDECESSOR,
    ) ||
    !exact(registry.sourcePolicyBinding, PLAYER_PHOTO_POLICY_V8_BINDING) ||
    !exact(
      registry.phaseEvidenceBindings,
      PLAYER_PHOTO_REGISTRY_V7_PHASE_EVIDENCE,
    ) ||
    !exact(
      registry.ownerAcceptedResidualRisks,
      PLAYER_PHOTO_REGISTRY_V7_OWNER_ACCEPTED_RESIDUAL_RISKS,
    ) ||
    registry.nonClearanceStatement !== DECISION_15_NON_CLEARANCE_STATEMENT ||
    !Array.isArray(registry.selections) ||
    registry.selections.length !== 21 ||
    !Array.isArray(predecessor.selections)
  ) {
    issues.push(
      malformedIssue(
        "registry v7 requires its exact lineage, evidence, risk, non-clearance, and 21-selection root",
      ),
    );
    return { issues, registry: null };
  }

  const predecessorByAthlete = new Map(
    predecessor.selections.map((selection) => [
      selection.athleteName,
      selection,
    ]),
  );
  const selectionNames = registry.selections.map(
    (selection) => selection.athleteName,
  );
  const expectedNames = [...input.expectedAthleteCases.keys()];
  if (!sameSortedSet(selectionNames, expectedNames)) {
    issues.push(
      issue(
        "player-photo-v7-roster",
        "selections",
        "registry v7 must map every athlete exactly once",
      ),
    );
  }

  const protectedRows = registry.selections
    .filter((selection) =>
      (DECISION_15_PROTECTED_ATHLETES as readonly string[]).includes(
        selection.athleteName,
      ),
    )
    .map((selection) => ({
      athleteName: selection.athleteName,
      localAssetSha256: selection.localFile.sha256,
      selectionSha256: sha256Hex(canonicalJson(selection)),
    }));
  issues.push(
    ...validateDecision15ProtectedCovers(protectedRows).map((entry) => ({
      ...entry,
      code: `player-photo-v7-${entry.code}`,
    })),
  );
  for (const athleteName of DECISION_15_PROTECTED_ATHLETES) {
    const current = registry.selections.find(
      (selection) => selection.athleteName === athleteName,
    );
    const previous = predecessorByAthlete.get(athleteName);
    if (
      current === undefined ||
      previous === undefined ||
      canonicalJson(current) !== canonicalJson(previous)
    ) {
      issues.push(
        issue(
          "player-photo-v7-protected-selection-drift",
          `selections.${athleteName}`,
          "all seven protected v6 selection subtrees must remain byte-for-byte canonical identical",
        ),
      );
    }
  }

  const promoted = registry.selections.filter(isDecision15PhotoSelectionV7);
  issues.push(
    ...validateDecision15TargetRoster(
      promoted.map((selection) => selection.athleteName),
    ).map((entry) => ({
      ...entry,
      code: `player-photo-v7-${entry.code}`,
    })),
  );

  for (const [index, selection] of promoted.entries()) {
    const path = `selections[${index}]`;
    const bytes = input.localAssetBytesByPath.get(selection.localFile.path);
    const expectedCases = input.expectedAthleteCases.get(selection.athleteName);
    if (bytes === undefined || expectedCases === undefined) {
      issues.push(
        issue(
          "player-photo-v7-local-or-mapping-missing",
          path,
          "each promoted photo needs exact local bytes and governed case mapping",
        ),
      );
      continue;
    }
    const source = selection.decision15Evidence.sourceEvidence;
    const marker = selection.decision15Evidence.rightsMarker;
    const projectedLicense =
      marker.rightsBucket === "public-domain"
        ? null
        : {
            name: marker.licenseName,
            token: marker.token,
            url: marker.rightsLinkOrStatementSource,
          };
    if (
      source.platform !== "wikimedia-commons" ||
      selection.coverKind !== "commons-photo" ||
      selection.currentCoverStatus !== "current" ||
      !exact(selection.caseIds, selection.decision15Evidence.caseIds) ||
      selection.athleteName !== selection.decision15Evidence.athleteName ||
      selection.nonEventCaption !==
        selection.decision15Evidence.nonInjuryCaption ||
      !exact(
        selection.focalPosition,
        selection.decision15Evidence.crop.focalPosition,
      ) ||
      !exact(selection.cropValidation, selection.decision15Evidence.crop) ||
      !exact(
        selection.localFile,
        selection.decision15Evidence.originalBinary.localFile,
      ) ||
      selection.commonsDescriptionUrl !==
        (source.platform === "wikimedia-commons"
          ? source.descriptionUrl
          : "") ||
      selection.commonsDownloadUrl !==
        (source.platform === "wikimedia-commons"
          ? source.originalFileUrl
          : "") ||
      selection.sourceRevision.id !==
        (source.platform === "wikimedia-commons" ? source.revisionId : -1) ||
      selection.sourceRevision.permalink !==
        (source.platform === "wikimedia-commons"
          ? source.revisionPermalink
          : "") ||
      selection.sourceRevision.timestamp !==
        (source.platform === "wikimedia-commons"
          ? source.revisionTimestamp
          : "") ||
      !exact(selection.license, projectedLicense) ||
      selection.photographerIdentity.name !== marker.displayedCredit.text ||
      selection.photographerIdentity.sourceUrl !==
        marker.displayedCredit.sourceUrl ||
      selection.rightsAttribution.licenseBucket !== marker.rightsBucket ||
      !exact(
        selection.rightsAttribution.adapterLicense,
        selection.decision15Evidence.crop.adapterLicense,
      ) ||
      selection.rightsAttribution.alterationState.disclosure !==
        marker.alterationDisclosure ||
      selection.rightsAttribution.alterationState.presentation !==
        selection.decision15Evidence.crop.presentation ||
      !exact(
        selection.rightsAttribution.displayedCredit,
        marker.displayedCredit,
      ) ||
      !exact(selection.rightsAttribution.workTitle, marker.workTitle) ||
      !exact(
        selection.rightsAttribution.copyrightNotice,
        marker.copyrightNotice,
      ) ||
      !exact(
        selection.rightsAttribution.disclaimerNotice,
        marker.disclaimerNotice,
      ) ||
      !exact(
        selection.rightsAttribution.otherPerFileNotice,
        marker.otherNotice,
      ) ||
      selection.supersession.previousLocalFilePath !==
        predecessorByAthlete.get(selection.athleteName)?.localFile.path ||
      selection.supersession.previousLocalFileSha256 !==
        predecessorByAthlete.get(selection.athleteName)?.localFile.sha256
    ) {
      issues.push(
        issue(
          "player-photo-v7-projection",
          path,
          "top-level rendering and attribution projections must exactly match Decision 15 evidence and v6 supersession",
        ),
      );
    }

    const eligibility = decideDecision15PhotoEligibility({
      candidate: selection.decision15Evidence,
      expectedCaseIds: expectedCases,
      localAssetBytes: bytes,
    });
    for (const entry of eligibility.issues) {
      issues.push({
        ...entry,
        code: `player-photo-v7-${entry.code}`,
        path: `${path}.${entry.path}`,
      });
    }
    if (
      !SHA1_RE.test(selection.originalMediaWikiSha1) ||
      sha1Hex(bytes) !== selection.originalMediaWikiSha1
    ) {
      issues.push(
        issue(
          "player-photo-v7-mediawiki-sha1",
          `${path}.originalMediaWikiSha1`,
          "the exact local original must match the frozen MediaWiki SHA-1",
        ),
      );
    }

    if (marker.rightsBucket === "cc-by-sa") {
      if (
        selection.usePolicy.mode !== "placement-rendition-only" ||
        !exact(
          selection.usePolicy.allowedUseKinds,
          DECISION_15_ALLOWED_BY_SA_USE_KINDS,
        ) ||
        !exact(
          selection.usePolicy.forbiddenUseKinds,
          DECISION_15_FORBIDDEN_BY_SA_USE_KINDS,
        )
      ) {
        issues.push(
          issue(
            "player-photo-v7-by-sa-firewall",
            `${path}.usePolicy`,
            "BY-SA works must be placement/rendition-only with the exact forbidden composition list",
          ),
        );
      }
      const allowed = decideDecision15BySaUse({
        adapterLicense: selection.cropValidation.adapterLicense,
        bakedOutput: false,
        licenseName: marker.licenseName ?? "",
        licenseToken: marker.token ?? "",
        licenseUrl: marker.rightsLinkOrStatementSource ?? "",
        siteComposed: false,
        useKind: "ordinary-html-css-placement",
      });
      const blocked = decideDecision15BySaUse({
        adapterLicense: selection.cropValidation.adapterLicense,
        bakedOutput: true,
        licenseName: marker.licenseName ?? "",
        licenseToken: marker.token ?? "",
        licenseUrl: marker.rightsLinkOrStatementSource ?? "",
        siteComposed: true,
        useKind: "og-image",
      });
      if (!allowed.allowed || blocked.allowed) {
        issues.push(
          issue(
            "player-photo-v7-by-sa-firewall",
            `${path}.usePolicy`,
            "the pure BY-SA policy must allow placement and reject composed/baked output",
          ),
        );
      }
    } else if (
      marker.rightsBucket === "public-domain"
        ? selection.usePolicy.mode !== "public-domain-placement"
        : selection.usePolicy.mode !== "ordinary-attributed-placement"
    ) {
      issues.push(
        issue(
          "player-photo-v7-use-policy",
          `${path}.usePolicy`,
          "non-BY-SA works must use their exact CC-attributed or public-domain placement mode",
        ),
      );
    }
  }

  const caseIds = registry.selections.flatMap((selection) => selection.caseIds);
  const expectedCaseIds = [...input.expectedAthleteCases.values()].flat();
  if (!sameSortedSet(caseIds, expectedCaseIds) || caseIds.length !== 26) {
    issues.push(
      issue(
        "player-photo-v7-case-mapping",
        "selections.caseIds",
        "all 26 governed cases must map exactly once",
      ),
    );
  }
  if (
    registry.selections.some(
      (selection) => selection.coverKind !== "commons-photo",
    )
  ) {
    issues.push(
      issue(
        "player-photo-v7-photo-count",
        "selections",
        "Decision 15 registry v7 must contain 21 photos and zero SVG fallbacks",
      ),
    );
  }

  const bucketCounts = new Map<string, number>();
  for (const selection of registry.selections) {
    const bucket = isDecision15PhotoSelectionV7(selection)
      ? selection.rightsAttribution.licenseBucket
      : selection.rightsAttribution.licenseBucket;
    bucketCounts.set(bucket, (bucketCounts.get(bucket) ?? 0) + 1);
  }
  if (
    bucketCounts.get("cc-by") !== 8 ||
    bucketCounts.get("cc-by-sa") !== 12 ||
    bucketCounts.get("public-domain") !== 1 ||
    bucketCounts.size !== 3
  ) {
    issues.push(
      issue(
        "player-photo-v7-rights-partition",
        "selections",
        "the final rights partition must be 8 CC BY, 12 CC BY-SA, and 1 public-domain photo",
      ),
    );
  }

  for (const selection of registry.selections) {
    const bytes = input.localAssetBytesByPath.get(selection.localFile.path);
    if (
      bytes === undefined ||
      bytes.byteLength !== selection.localFile.byteLength ||
      sha256Hex(bytes) !== selection.localFile.sha256
    ) {
      issues.push(
        issue(
          "player-photo-v7-local-byte-drift",
          selection.localFile.path,
          "every selected local photo must match its exact recorded bytes",
        ),
      );
    }
  }

  return { issues, registry };
}
